SUITES_MAIN = ["final_ruler", "final_longbench", "final_locomo"]
SUITE_LABEL = {
    "final_ruler": "RULER",
    "final_longbench": "LongBench",
    "final_locomo": "LoCoMo",
    "final_kvcompare": "KV-compress pilot",
}
